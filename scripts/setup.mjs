#!/usr/bin/env node
// Generates local secrets (git-ignored) and configures the Convex local deployment env.
// Safe to re-run: existing secrets are kept.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const ENV_FILE = ".env";
const KEY_FILE = ".secrets/n8n_encryption_key";

function readEnv(path) {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split("\n")
      .filter((l) => l && !l.startsWith("#") && l.includes("="))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
  );
}

const env = readEnv(ENV_FILE);
const local = readEnv(".env.local");
const secret = () => randomBytes(32).toString("hex");

env.APP_TIMEZONE ||= "America/Sao_Paulo";
env.APP_URL ||= "http://localhost:3000";
env.OPS_ALERT_EMAIL ||= "ops@lendloop.local";
env.LENDLOOP_WEBHOOK_SECRET ||= secret();
env.LENDLOOP_AUTOMATION_SECRET ||= secret();

const siteUrl = local.NEXT_PUBLIC_CONVEX_SITE_URL;
if (!siteUrl) {
  console.error("Run `npx convex dev --once` first so .env.local has NEXT_PUBLIC_CONVEX_SITE_URL.");
  process.exit(1);
}
// n8n runs in Docker and reaches the host's Convex through host.docker.internal.
env.LENDLOOP_CONVEX_URL_FROM_N8N = siteUrl.replace(/127\.0\.0\.1|localhost/, "host.docker.internal");

writeFileSync(
  ENV_FILE,
  "# Generated by `npm run setup` — local only, never commit.\n" +
    Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") +
    "\n",
  { mode: 0o600 },
);

if (!existsSync(KEY_FILE)) {
  mkdirSync(".secrets", { recursive: true, mode: 0o700 });
  // 0644 inside a 0700 dir: unreadable by other host users, readable by the n8n container user.
  writeFileSync(KEY_FILE, secret(), { mode: 0o644 });
}

const convexEnv = {
  LENDLOOP_WEBHOOK_SECRET: env.LENDLOOP_WEBHOOK_SECRET,
  LENDLOOP_AUTOMATION_SECRET: env.LENDLOOP_AUTOMATION_SECRET,
  N8N_LOAN_EVENTS_URL: "http://localhost:5678/webhook/lendloop/loan-events",
  APP_TIMEZONE: env.APP_TIMEZONE,
  APP_URL: env.APP_URL,
  ALLOW_SEED: "true",
};
if (local.CLERK_JWT_ISSUER_DOMAIN) convexEnv.CLERK_JWT_ISSUER_DOMAIN = local.CLERK_JWT_ISSUER_DOMAIN;
for (const [k, v] of Object.entries(convexEnv)) {
  execFileSync("npx", ["convex", "env", "set", k, v], { stdio: ["ignore", "ignore", "inherit"] });
  console.log(`convex env: ${k} set`);
}
if (!local.CLERK_JWT_ISSUER_DOMAIN) {
  console.warn("CLERK_JWT_ISSUER_DOMAIN missing in .env.local — add it and re-run setup.");
}
console.log("Setup done. Next: docker compose up -d && npm run dev");
